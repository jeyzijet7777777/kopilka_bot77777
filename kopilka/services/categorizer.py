# Морфологический стеммер (Russian Snowball Stemmer)
_PERFECTIVEGERUND = re.compile(r"((?:[ая](?:в|вши|вшись))|(?:ив|ивши|ившись|ыв|ывши|ывшись))$")
_REFLEXIVE = re.compile(r"(с[яь])$")
_ADJECTIVE = re.compile(r"(ее|ие|ые|ое|ими|ыми|ей|ий|ый|ой|ем|им|ым|ом|его|ого|ему|ому|их|ых|ую|юю|ая|яя|ою|ею)$")
_PARTICIPLE = re.compile(r"((?:[ая](?:ем|нн|вш|ющ|щ))|(?:ивш|ывш|ующ))$")
_VERB = re.compile(r"((?:[ая](?:ла|на|ете|йте|ли|й|л|ем|н|ло|но|ет|ют|ны|ть|ешь|нно))|(?:ила|ыла|ена|ейте|уйте|ите|или|ыли|ей|уй|ил|ыл|им|ым|ен|ило|ыло|ено|ят|ует|уют|ит|ыт|ены|ить|ыть|ишь|ую|ю))$")
_NOUN = re.compile(r"(а|ев|ов|ие|ье|е|иями|ями|ами|еи|ии|и|ией|ей|ой|ий|й|иям|ям|ием|ем|ам|ом|о|у|ах|иях|ях|ы|ь|ию|ью|ю|я)$")
_SUPERLATIVE = re.compile(r"(ейш|ейше)$")
_DERIVATIONAL = re.compile(r"[^аеиоуыэюя]+(ост|ость)$")


def stem_ru(word: str) -> str:
    """Нормализует русское слово к его неизменяемой основе (стем)."""
    word = word.lower().replace("ё", "е").strip()
    m = re.search(r"[аеиоуыэюя]", word)
    if not m:
        return word
    p = m.start() + 1
    rv = word[p:]

    m_pg = _PERFECTIVEGERUND.search(rv)
    if m_pg:
        rv = rv[:m_pg.start()]
    else:
        m_ref = _REFLEXIVE.search(rv)
        if m_ref:
            rv = rv[:m_ref.start()]
        m_adj = _ADJECTIVE.search(rv)
        if m_adj:
            rv = rv[:m_adj.start()]
            m_part = _PARTICIPLE.search(rv)
            if m_part:
                rv = rv[:m_part.start()]
        else:
            m_verb = _VERB.search(rv)
            if m_verb:
                rv = rv[:m_verb.start()]
            else:
                m_noun = _NOUN.search(rv)
                if m_noun:
                    rv = rv[:m_noun.start()]

    if rv.endswith("и"):
        rv = rv[:-1]
    m_der = _DERIVATIONAL.search(rv)
    if m_der:
        rv = rv[:m_der.start(1)]
    m_sup = _SUPERLATIVE.search(rv)
    if m_sup:
        rv = rv[:m_sup.start()]
    if rv.endswith("нн"):
        rv = rv[:-1]
    if rv.endswith("ь"):
        rv = rv[:-1]
    return word[:p] + rv


def _clean_token(s: str) -> str:
    return " ".join(str(s).casefold().replace("ё", "е").split())


# --- Построение индексов поиска ---
_EXACT_INDEX: dict[str, str] = {}
_STEMMED_INDEX: dict[str, str] = {}
_MULTIWORD_KEYWORDS: list[tuple[str, str]] = []
_ALL_KEYWORDS_SET: set[str] = set()

for cat_name, info in CATEGORIES_CATALOG.items():
    # Синонимы категории
    for syn in info["synonyms"]:
        clean_syn = _clean_token(syn)
        _EXACT_INDEX[clean_syn] = cat_name
        _ALL_KEYWORDS_SET.add(clean_syn)
        st = stem_ru(clean_syn)
        if len(st) >= 3 and st not in _STEMMED_INDEX:
            _STEMMED_INDEX[st] = cat_name

    # Ключевые слова
    for kw in info["keywords"]:
        clean_kw = _clean_token(kw)
        _EXACT_INDEX[clean_kw] = cat_name
        _ALL_KEYWORDS_SET.add(clean_kw)

        if " " in clean_kw:
            _MULTIWORD_KEYWORDS.append((clean_kw, cat_name))
        else:
            st = stem_ru(clean_kw)
            if len(st) >= 3 and st not in _STEMMED_INDEX:
                _STEMMED_INDEX[st] = cat_name

# Сортируем многословные ключи по убыванию длины, чтобы длинные фразы («яндекс такси») имели приоритет
_MULTIWORD_KEYWORDS.sort(key=lambda x: len(x[0]), reverse=True)
_ALL_KEYWORDS_LIST: list[str] = sorted(_ALL_KEYWORDS_SET, key=len, reverse=True)


def get_user_category_rule(user_id: int, keyword: str) -> str | None:
    """Проверяет сохранённое пользователем правило для слова."""
    k = _clean_token(keyword)
    if not k:
        return None
    try:
        with db() as conn:
            row = conn.execute(
                "SELECT value FROM settings WHERE user_id = ? AND key = ?",
                (user_id, f"cat_rule_{k}"),
            ).fetchone()
            return row["value"] if row else None
    except Exception:
        return None


def save_user_category_rule(user_id: int, keyword: str, category: str):
    """Запоминает выбор пользователя для ключевого слова."""
    k = _clean_token(keyword)
    if not k or not category:
        return
    try:
        with db() as conn:
            conn.execute(
                "INSERT INTO settings (user_id, key, value) VALUES (?, ?, ?) "
                "ON CONFLICT(user_id, key) DO UPDATE SET value = excluded.value",
                (user_id, f"cat_rule_{k}", str(category).strip()),
            )
    except Exception:
        pass


def _find_user_matching_category(target_category: str, user_existing_categories: list[str] | None) -> str:
    """Если у пользователя уже есть подходящая категория-синоним (например «Еда» вместо «Продукты»),
    возвращает её. Иначе возвращает target_category.
    """
    if not user_existing_categories:
        return target_category

    target_clean = _clean_token(target_category)
    existing_map = {_clean_token(c): c for c in user_existing_categories}

    # Точное совпадение
    if target_clean in existing_map:
        return existing_map[target_clean]

    # Проверяем синонимы из каталога
    info = CATEGORIES_CATALOG.get(target_category)
    if info:
        for syn in info["synonyms"]:
            syn_clean = _clean_token(syn)
            if syn_clean in existing_map:
                return existing_map[syn_clean]

    return target_category


def classify_expense(
    user_id: int,
    text: str,
    user_existing_categories: list[str] | None = None,
) -> tuple[str, str | None]:
    """Умная классификация текста траты в подходящую категорию.

    Поддерживает:
    - Персональные правила пользователя.
    - Точные совпадения и многословные ключевые слова.
    - Морфологический стемминг (падежи, окончания -у, -е, -а и т.д.).
    - Игнорирование предлогов («в», «на», «за» и др.).
    - Нечёткий поиск (fuzzy matching difflib) при опечатках.

    Возвращает (итоговая_категория, совпавшее_ключевое_слово_или_None).
    """
    cleaned = _clean_token(text)
    if not cleaned:
        return "Разное", None

    user_existing = user_existing_categories or []

    # 1. Сначала проверяем персональные правила пользователя для всей фразы целиком
    rule_cat = get_user_category_rule(user_id, cleaned)
    if rule_cat:
        return rule_cat, cleaned

    # Проверяем токены на пользовательские правила
    raw_tokens = [t for t in _WORD_SPLIT_RE.split(cleaned) if len(t) >= 2]
    for t in raw_tokens:
        rule_cat = get_user_category_rule(user_id, t)
        if rule_cat:
            return rule_cat, t

    # 2. Прямое точное совпадение всей строки с каталогом
    if cleaned in _EXACT_INDEX:
        target = _EXACT_INDEX[cleaned]
        best_cat = _find_user_matching_category(target, user_existing)
        return best_cat, cleaned

    # 3. Поиск многословных ключевых фраз (например: «яндекс такси», «додо пицца», «билеты в кино»)
    for multi_kw, target in _MULTIWORD_KEYWORDS:
        if multi_kw in cleaned:
            best_cat = _find_user_matching_category(target, user_existing)
            return best_cat, multi_kw

    # 4. Токенизация и фильтрация стоп-слов
    meaningful_tokens = [t for t in raw_tokens if t not in STOPWORDS_RU and len(t) >= 2]
    tokens_to_check = meaningful_tokens if meaningful_tokens else raw_tokens

    # Проверяем каждое значимое слово на точное совпадение
    for t in tokens_to_check:
        if t in _EXACT_INDEX:
            target = _EXACT_INDEX[t]
            best_cat = _find_user_matching_category(target, user_existing)
            return best_cat, t

    # 5. Морфологический стемминг (поиск основы слова)
    for t in tokens_to_check:
        st = stem_ru(t)
        if len(st) >= 3 and st in _STEMMED_INDEX:
            target = _STEMMED_INDEX[st]
            best_cat = _find_user_matching_category(target, user_existing)
            return best_cat, t

    # 6. Проверка биграмм и триграмм со стеммингом
    n = len(tokens_to_check)
    for l in (3, 2):
        for i in range(n - l + 1):
            ngram = " ".join(tokens_to_check[i : i + l])
            if ngram in _EXACT_INDEX:
                target = _EXACT_INDEX[ngram]
                best_cat = _find_user_matching_category(target, user_existing)
                return best_cat, ngram

    # 7. Нечёткий поиск (fuzzy matching) для слов от 4 букв (опечатки вроде «вкусвил», «вайлдбериз», «додошка»)
    for t in tokens_to_check:
        if len(t) >= 4:
            close = difflib.get_close_matches(t, _ALL_KEYWORDS_LIST, n=1, cutoff=0.78)
            if close:
                matched_kw = close[0]
                target = _EXACT_INDEX[matched_kw]
                best_cat = _find_user_matching_category(target, user_existing)
                return best_cat, t

    # 8. Проверка на вхождение префиксов/корней (от 4 букв)
    for t in tokens_to_check:
        if len(t) >= 4:
            for kw, target in _EXACT_INDEX.items():
                if len(kw) >= 4 and (t.startswith(kw) or kw.startswith(t)):
                    best_cat = _find_user_matching_category(target, user_existing)
                    return best_cat, t

    # Не найдено совпадений
    return "Разное", None


def recategorize_user_expenses(user_id: int | None = None, db_path: str = None) -> dict:
    """Проходит по всем тратам (или тратам конкретного user_id)
    и обновляет категории, которые соответствуют ключевым словам/товарам/брендам
    из каталога или персональным правилам.
    """
    with db(db_path) as conn:
        if user_id is not None:
            rows = conn.execute(
                "SELECT id, user_id, category FROM expenses WHERE user_id = ? ORDER BY id",
                (user_id,),
            ).fetchall()
        else:
            rows = conn.execute(
                "SELECT id, user_id, category FROM expenses ORDER BY id"
            ).fetchall()

        # Категории, которые уже использовались пользователями
        user_cats_map: dict[int, list[str]] = {}
        for r in conn.execute("SELECT DISTINCT user_id, category FROM expenses").fetchall():
            user_cats_map.setdefault(r["user_id"], []).append(r["category"])

        changes: dict[tuple[str, str], int] = {}
        updated_count = 0

        for r in rows:
            uid = r["user_id"]
            old_cat = r["category"]
            exp_id = r["id"]

            existing = user_cats_map.get(uid, [])
            filtered_existing = [c for c in existing if _clean_token(c) != _clean_token(old_cat)]
            new_cat, matched_kw = classify_expense(uid, old_cat, filtered_existing)

            # Если найдено совпадение по каталогу и категория изменилась
            if matched_kw and new_cat and new_cat != "Разное" and _clean_token(new_cat) != _clean_token(old_cat):
                conn.execute("UPDATE expenses SET category = ? WHERE id = ?", (new_cat, exp_id))
                changes[(old_cat, new_cat)] = changes.get((old_cat, new_cat), 0) + 1
                updated_count += 1

        return {
            "total_scanned": len(rows),
            "updated_count": updated_count,
            "changes": changes,
        }
