# Морфологический стеммер (Russian Snowball Stemmer)
_PERFECTIVEGERUND = re.compile(r"((?:[ая](?:в|вши|вшись))|(?:ив|ивши|ившись|ыв|ывши|ывшись))$")
_REFLEXIVE = re.compile(r"(с[яь])$")
_ADJECTIVE = re.compile(r"(ее|ие|ые|ое|ими|ыми|ей|ий|ый|ой|ем|им|ым|ом|его|ого|ему|ому|их|ых|ую|юю|ая|яя|ою|ею)$")
_PARTICIPLE = re.compile(r"((?:[ая](?:ем|нн|вш|ющ|щ))|(?:ивш|ывш|ующ))$")
_VERB = re.compile(r"((?:[ая](?:ла|на|ете|йте|ли|й|л|ем|н|ло|но|ет|ют|ны|ть|ешь|нно))|(?:ила|ыла|ена|ейте|уйте|ите|или|ыли|ей|уй|ил|ыл|им|ым|ен|ило|ыло|ено|ят|ует|уют|ит|ыт|ены|ить|ыть|ишь|ую|ю))$")
_NOUN = re.compile(r"(а|ев|ов|ие|ье|е|иями|ями|ами|еи|ии|и|ией|ей|ой|ий|й|иям|ям|ием|ем|ам|ом|о|у|ах|иях|ях|ы|ь|ию|ью|ю|я)$")
_SUPERLATIVE = re.compile(r"(ейш|ейше)$")
_DERIVATIONAL = re.compile(r"[^аеиоуыэюя]+(ост|ость)$")
_DIMINUTIVE_RE = re.compile(r"(очк|ечк|еньк|оньк|ушк|юшк|ышк|ишк|чик|щик|к)$")


def stem_ru(word: str) -> str:
    """Нормализует русское слово к его неизменяемой основе (стем)."""
    word = word.lower().replace("ё", "е").strip()
    m = re.search(r"[аеиоуыэюя]", word)
    if not m:
        return word
    p = m.start() + 1
    rv = word[p:]

    m_pg = _PERFECTIVEGERUND.search(rv)
    if m_pg:
        rv = rv[:m_pg.start()]
    else:
        m_ref = _REFLEXIVE.search(rv)
        if m_ref:
            rv = rv[:m_ref.start()]
        m_adj = _ADJECTIVE.search(rv)
        if m_adj:
            rv = rv[:m_adj.start()]
            m_part = _PARTICIPLE.search(rv)
            if m_part:
                rv = rv[:m_part.start()]
        else:
            m_verb = _VERB.search(rv)
            if m_verb:
                rv = rv[:m_verb.start()]
            else:
                m_noun = _NOUN.search(rv)
                if m_noun:
                    rv = rv[:m_noun.start()]

    if rv.endswith("и"):
        rv = rv[:-1]
    m_der = _DERIVATIONAL.search(rv)
    if m_der:
        rv = rv[:m_der.start(1)]
    m_sup = _SUPERLATIVE.search(rv)
    if m_sup:
        rv = rv[:m_sup.start()]
    if rv.endswith("нн"):
        rv = rv[:-1]
    if rv.endswith("ь"):
        rv = rv[:-1]
    return word[:p] + rv


def _diminutive_stems(word: str) -> list[str]:
    """Генерирует дополнительные основы без уменьшительно-ласкательных суффиксов
    («мороженка» -> «морожен», «печеньки» -> «печен», «конфетки» -> «конфет»).
    """
    st = stem_ru(word)
    out = [st]
    m = _DIMINUTIVE_RE.search(st)
    if m and m.start() >= 3:
        base = st[:m.start()]
        out.append(base)
        if base.endswith("ь"):
            out.append(base[:-1])
    return out


def _clean_token(s: str) -> str:
    return " ".join(str(s).casefold().replace("ё", "е").split())


