_WORD_SPLIT_RE = re.compile(r"[\s,;:.!?-]+")


def _clean_token(s: str) -> str:
    return " ".join(str(s).casefold().replace("ё", "е").split())


# Кэш быстрого поиска: keyword -> category_name
_KEYWORD_INDEX: dict[str, str] = {}
for cat_name, info in CATEGORIES_CATALOG.items():
    for kw in info["keywords"]:
        _KEYWORD_INDEX[_clean_token(kw)] = cat_name
    for syn in info["synonyms"]:
        _KEYWORD_INDEX[_clean_token(syn)] = cat_name


def get_user_category_rule(user_id: int, keyword: str) -> str | None:
    """Проверяет сохранённое пользователем правило для слова."""
    k = _clean_token(keyword)
    if not k:
        return None
    try:
        with db() as conn:
            row = conn.execute(
                "SELECT value FROM settings WHERE user_id = ? AND key = ?",
                (user_id, f"cat_rule_{k}"),
            ).fetchone()
            return row["value"] if row else None
    except Exception:
        return None


def save_user_category_rule(user_id: int, keyword: str, category: str):
    """Запоминает выбор пользователя для ключевого слова."""
    k = _clean_token(keyword)
    if not k or not category:
        return
    try:
        with db() as conn:
            conn.execute(
                "INSERT INTO settings (user_id, key, value) VALUES (?, ?, ?) "
                "ON CONFLICT(user_id, key) DO UPDATE SET value = excluded.value",
                (user_id, f"cat_rule_{k}", str(category).strip()),
            )
    except Exception:
        pass


def _find_user_matching_category(target_category: str, user_existing_categories: list[str]) -> str:
    """Если у пользователя уже есть подходящая категория-синоним (например «Еда» вместо «Продукты»),

    возвращает её. Иначе возвращает target_category.
    """
    if not user_existing_categories:
        return target_category

    target_clean = _clean_token(target_category)
    existing_map = {_clean_token(c): c for c in user_existing_categories}

    # Точное совпадение
    if target_clean in existing_map:
        return existing_map[target_clean]

    # Проверяем синонимы из каталога
    info = CATEGORIES_CATALOG.get(target_category)
    if info:
        for syn in info["synonyms"]:
            syn_clean = _clean_token(syn)
            if syn_clean in existing_map:
                return existing_map[syn_clean]

    return target_category


